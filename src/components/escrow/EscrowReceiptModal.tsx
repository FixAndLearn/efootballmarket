"use client";

import React, { useRef } from "react";
import { Order } from "@/types/database";
import { Button } from "@/components/ui/Button";
import { formatCurrency, getPlatformLabel } from "@/lib/utils";
import { CheckCircle2, Copy, FileText, Printer, X } from "lucide-react";
import { useState } from "react";

export interface EscrowReceiptModalProps {
  order: Order;
  status: string;
  isOpen: boolean;
  onClose: () => void;
}

export function EscrowReceiptModal({ order, status, isOpen, onClose }: EscrowReceiptModalProps) {
  const [copied, setCopied] = useState(false);
  const receiptRef = useRef<HTMLDivElement>(null);

  if (!isOpen) return null;

  const recordReference = `ORD-${order.order_number}-${order.id.slice(0, 8).toUpperCase()}`;
  const orderCreatedDate = new Date(order.created_at).toLocaleString("en-KE", {
    dateStyle: "medium",
    timeStyle: "short",
  });
  const statusLabel: Record<string, string> = {
    payment_pending: "Payment confirmation pending",
    escrow_locked: "Payment recorded · seller delivery pending",
    seller_delivered: "Delivery submitted · buyer inspection pending",
    buyer_reviewing: "Buyer inspection in progress",
    completed: "Order completed · seller proceeds released to available balance",
    disputed: "Dispute open · resolution pending",
    cancelled: "Order cancelled · this record does not confirm a refund",
    refunded: "Refund decision recorded · manual transfer unconfirmed",
  };
  const currentStatusLabel = statusLabel[status] || "Order status recorded";

  const handlePrint = () => {
    window.print();
  };

  const handleCopyReference = async () => {
    try {
      await navigator.clipboard.writeText(recordReference);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md overflow-y-auto animate-in fade-in">
      <div className="relative w-full max-w-2xl bg-sx-subtle border border-sx-border-strong rounded-3xl shadow-2xl p-6 sm:p-8 my-8 text-sx-ink">
        {/* Modal Controls (Hidden in Print) */}
        <div className="flex items-center justify-between pb-4 border-b border-sx-border mb-6 print:hidden">
          <div className="flex items-center gap-2">
            <span className="p-2 rounded-xl bg-sx-stone text-sx-muted">
              <FileText className="w-5 h-5" />
            </span>
            <div>
              <h3 className="text-base font-bold text-sx-ink">Marketplace Order Record</h3>
              <p className="text-xs text-sx-muted">System status summary · not an M-Pesa receipt</p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="p-2 rounded-xl bg-sx-stone hover:bg-sx-elevated text-sx-muted hover:text-sx-ink transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Printable Voucher Paper */}
        <div
          ref={receiptRef}
          id="official-escrow-receipt"
          className="bg-sx-canvas p-6 sm:p-8 rounded-2xl border border-sx-border space-y-6 text-sx-ink-soft print:bg-white print:text-black print:border-none print:p-0"
        >
          {/* Header Banner */}
          <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 border-b border-sx-border print:border-gray-300 pb-5">
            <div>
              <div className="flex items-center gap-2 mb-1">
                <span className="text-lg font-black tracking-tight text-sx-ink print:text-black font-display">
                  eFootballMarket Kenya
                </span>
                <span className="text-[10px] font-bold px-2 py-0.5 rounded bg-sx-stone border border-sx-border text-sx-muted print:bg-gray-100 print:text-black">
                  ORDER RECORD
                </span>
              </div>
              <p className="text-xs text-sx-muted print:text-sx-muted">
                Marketplace order status and amount summary
              </p>
              <p className="text-xs text-sx-muted print:text-sx-muted font-medium">
                This record is generated by eFootballMarket; it is not a provider-issued payment receipt.
              </p>
            </div>

            <div className="text-left sm:text-right text-xs">
              <span className="block text-sx-muted print:text-sx-muted uppercase text-[10px] font-bold">
                Record Reference
              </span>
              <span className="font-mono font-bold text-sx-amber-text print:text-black text-sm block">
                {recordReference}
              </span>
              <span className="text-sx-muted print:text-sx-muted text-[11px] block mt-0.5">
                Order created: {orderCreatedDate}
              </span>
            </div>
          </div>

          {/* Certificate Stamp Box */}
          <div className="p-3.5 rounded-xl bg-sx-stone border border-sx-border print:bg-gray-50 print:border-gray-300 flex items-center gap-2 text-xs">
            {status === "completed" ? (
              <CheckCircle2 className="w-4 h-4 text-sx-green-text print:text-emerald-600 shrink-0" />
            ) : (
              <FileText className="w-4 h-4 text-sx-muted shrink-0" />
            )}
            <span className="text-sx-ink-soft print:text-black font-semibold">
              Current system status: {currentStatusLabel}
            </span>
          </div>

          {/* Asset & Order Details Grid */}
          <div className="grid grid-cols-2 gap-4 text-xs">
            <div>
              <span className="text-sx-muted print:text-sx-muted block text-[10px] uppercase font-bold">
                Account Item / Squad
              </span>
              <span className="font-bold text-sx-ink print:text-black text-sm block mt-0.5">
                {order.listing?.title || "eFootball Account"}
              </span>
              <span className="text-sx-muted print:text-sx-muted text-[11px]">
                Platform: {order.listing?.platform ? getPlatformLabel(order.listing.platform) : "Mobile/Console"} / OVR {order.listing?.overall_team_strength || "Elite"}
              </span>
            </div>

            <div>
              <span className="text-sx-muted print:text-sx-muted block text-[10px] uppercase font-bold">
                Order Reference
              </span>
              <span className="font-mono font-bold text-sx-ink-soft print:text-black text-sm block mt-0.5">
                Order #{order.order_number}
              </span>
              <span className="text-sx-muted print:text-sx-muted text-[11px]">
                Internal ID: {order.id.slice(0, 13)}
              </span>
            </div>
          </div>

          {/* Counterparties Summary */}
          <div className="p-4 rounded-xl bg-sx-subtle print:bg-gray-50 border border-sx-border print:border-gray-200 grid grid-cols-2 gap-4 text-xs">
            <div>
              <span className="text-[10px] uppercase font-bold text-sx-muted print:text-sx-muted block">
                Purchaser (Buyer)
              </span>
              <span className="font-semibold text-sx-ink-soft print:text-black block mt-0.5">
                {order.buyer?.username || "Buyer account"}
              </span>
              <span className="text-[11px] text-sx-muted print:text-sx-muted">
                Listed as the buyer on this order
              </span>
            </div>

            <div>
              <span className="text-[10px] uppercase font-bold text-sx-muted print:text-sx-muted block">
                Vendor (Seller)
              </span>
              <span className="font-semibold text-sx-ink-soft print:text-black block mt-0.5">
                {order.seller?.username || "Seller account"}
              </span>
              <span className="text-[11px] text-sx-muted print:text-sx-muted">
                Listed as the seller on this order
              </span>
            </div>
          </div>

          {/* Financial Ledger Breakdown */}
          <div className="border-t border-sx-border print:border-gray-300 pt-4 space-y-2 text-xs">
            <div className="flex justify-between text-sx-ink-soft print:text-gray-700">
              <span>Order amount recorded in the app</span>
              <span className="font-mono">{formatCurrency(order.total_amount, order.currency)}</span>
            </div>
            <div className="flex justify-between text-sx-muted print:text-sx-muted">
              <span>Marketplace platform fee</span>
              <span className="font-mono text-sx-green-text print:text-black">
                {order.platform_fee != null ? formatCurrency(order.platform_fee, order.currency) : "Not recorded"}
              </span>
            </div>
            <div className="flex justify-between text-sx-muted print:text-sx-muted">
              <span>Provider payment receipt / reference</span>
              <span className="font-mono text-sx-muted print:text-black">Not displayed in this order record</span>
            </div>
            <div className="flex justify-between text-sm font-extrabold text-sx-ink print:text-black pt-2 border-t border-sx-border print:border-gray-300">
              <span>Order amount recorded</span>
              <span className="font-mono text-sx-green-text print:text-black">
                {formatCurrency(order.total_amount, order.currency)}
              </span>
            </div>
          </div>

          {/* Scope of this system-generated record */}
          <div className="pt-3 border-t border-sx-border print:border-gray-200 text-[10px] text-sx-muted print:text-sx-muted leading-relaxed space-y-1">
            <p>
              <strong>Record scope:</strong> This page summarizes the order data held by eFootballMarket. It is not an M-Pesa or Safaricom receipt and does not prove that a provider payment, seller withdrawal, or manual refund transfer was sent. Use the provider-issued transaction receipt to verify an M-Pesa payment; contact support about any manual transfer.
            </p>
          </div>

          {/* Official Sign-off & Director Seal */}
          <div className="pt-4 border-t border-sx-border print:border-gray-300 flex flex-col sm:flex-row items-start sm:items-end justify-between gap-3 text-xs">
            <div>
              <span className="block text-[10px] uppercase font-bold text-sx-muted print:text-sx-muted">
                Record Source
              </span>
              <span className="font-bold text-sx-ink print:text-black block text-sm mt-0.5">
                eFootballMarket order system
              </span>
              <span className="text-[11px] text-sx-muted print:text-sx-muted">
                For questions, contact support through the website.
              </span>
            </div>

            <div className="text-left sm:text-right text-[10px] text-sx-muted print:text-sx-muted font-mono">
              <span>Record reference:</span>
              <span className="block">{recordReference}</span>
            </div>
          </div>
        </div>

        {/* Action Controls (Hidden in Print) */}
        <div className="mt-6 flex flex-wrap items-center justify-between gap-3 print:hidden">
          <Button variant="outline" size="sm" onClick={handleCopyReference}>
            <Copy className="w-3.5 h-3.5 mr-1.5" />
            {copied ? "Copied Record Reference" : "Copy Record Reference"}
          </Button>

          <div className="flex items-center gap-3">
            <Button variant="primary" size="md" onClick={handlePrint}>
              <Printer className="w-4 h-4 mr-1.5" />
              Print / Save PDF Receipt
            </Button>
            <Button variant="secondary" size="md" onClick={onClose}>
              Close
            </Button>
          </div>
        </div>
      </div>
    </div>
  );
}
